/** 全部主题（核心 + 扩展），图鉴/足迹/地图统一入口 */
export const ALL_THEMES = [...CULTURE_THEMES, ...EXTENDED_THEMES];

const THEME_INDEX = new Map(ALL_THEMES.map(t => [t.themeId, t]));

/** 主题是否有事实卡（核心主题才有；扩展主题讲解走联网搜索） */
export function hasFactCard(theme) {
  return !!(theme && Array.isArray(theme.facts) && theme.facts.length > 0);
}

/** 按 ID 取主题（两级合并查询） */
export function getThemeById(themeId) {
  return THEME_INDEX.get(themeId) || null;
}

/** 按 AI 识别主体文本匹配主题（识别描述 → keywords/aliases 命中，核心+扩展两级） */
export function matchThemeByText(text) {
  if (!text) return null;
  for (const t of ALL_THEMES) {
    const dict = [...t.keywords, ...t.aliases, t.name];
    if (dict.some(k => text.includes(k))) return t;
  }
  return null;
}

/** 匹配与某主题关联的画廊作品（title/tags/description 关键词） */
export function matchArtworksByTheme(artworks, themeId) {
  const theme = getThemeById(themeId);
  if (!theme || !Array.isArray(artworks)) return [];
  return artworks.filter(a => {
    const hay = `${a.title || ''} ${a.tags ? a.tags.join(',') : ''} ${a.description || ''}`;
    return theme.worksMatch.some(k => hay.includes(k));
  });
}
